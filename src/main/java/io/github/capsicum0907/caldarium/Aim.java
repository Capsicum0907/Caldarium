package io.github.capsicum0907.caldarium;

/**
 * What a block does through the one face it is aimed at, which for the three that
 * carry is the only thing telling them apart. ⭐ A door is a cable with one of these
 * on it; everything else about the three is the same.
 */
public enum Aim {
    /** Nothing. A cable is not aimed anywhere. */
    NONE,
    /** Draws out of what is there, for machines that wait to be asked. */
    DRAWS,
    /** Gives to what is there, which is the only way out of the line. */
    GIVES
}
